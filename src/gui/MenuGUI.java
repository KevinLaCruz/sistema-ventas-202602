    private void repProductoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_repProductoActionPerformed
        // TODO add your handling code here:
        try {
            Connection cn = ConexionMySQL.getInstance().getCn();
            String dir = System.getProperty("user.dir") + "\\src\\reporte\\repProducto.jrxml";
            JasperReport rep = JasperCompileManager.compileReport(dir);
            JasperPrint showRep = JasperFillManager.fillReport(rep, null, cn);
            JasperViewer v = new JasperViewer(showRep, false);
            v.setTitle("REPORTE DE PRODUCTO");
            v.setExtendedState(MAXIMIZED_BOTH);
            v.setVisible(true);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error: " + e);
        }
    }//GEN-LAST:event_repProductoActionPerformed

