    private void habilitarControles(boolean b) {
        txtCantidad.setEditable(b);
        btnBuscarCliente.setEnabled(b);
        btnBuscarEmpleado.setEnabled(b);
        btnBuscarProducto.setEnabled(b);
        btnAgregar.setEnabled(b);
        btnQuitar.setEnabled(b);
        btnGrabar.setEnabled(b);
        btnCancelar.setEnabled(b);
        btnNuevo.setEnabled(!b);
        btnSalir.setEnabled(!b);
        txtCantidad.grabFocus();
    }

    private void limpiarControles() {
        limpiarTable();
        JTextField[] txt = {txtFactura, txtFecha, txtCodCliente, txtNombClie, txtCodEmpleado, txtNombEmpl, txtApatEmpl, txtAmatEmpl, txtCodProducto, txtNombProd, txtCantidad, txtImporte};
        for (JTextField t : txt) {
            t.setText(null);
        }
    }

    private void limpiarTable() {
        if (dtm.getRowCount() > 0) {
            dtm.setRowCount(0);
        }
    }
