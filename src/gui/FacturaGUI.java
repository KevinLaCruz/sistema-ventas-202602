    private void limpiarControles() {
        limpiarTable();
        JTextField[] txt = {txtFactura, txtFecha, txtCodCliente, txtNombClie, txtCodEmpleado, txtNombEmpl, txtApatEmpl, txtAmatEmpl, txtCodProducto, txtNombProd, txtCantidad, txtImporte, txtSubTotal, txtIgv, txtTotal};
        for (JTextField t : txt) {
            t.setText(null);
        }
        subTotal = 0.0;
        igv = 0.0;
        total = 0.0;
        precio = 0.0;
        importe = 0.0;
    }

    private void limpiarTable() {
        if (dtm.getRowCount() > 0) {
            dtm.setRowCount(0);
        }
    }

    public static void calcularImporte() {
        importe = 0.0;
        String textoCantidad = txtCantidad.getText().trim();
        if (textoCantidad.isEmpty()) {
            txtImporte.setText("");
            return;
        }
        int cantidad = Integer.parseInt(textoCantidad);
        if (cantidad <= 0) {
            txtImporte.setText("");
            return;
        }
        importe = precio * cantidad;
        txtImporte.setText(String.valueOf(importe));
    }

    private void limpiarProducto() {
        txtCodProducto.setText("");
        txtNombProd.setText("");
        txtCantidad.setText("");
        txtImporte.setText("");
        precio = 0.0;
        importe = 0.0;
    }

    private void calcularTotales() {
        subTotal = 0.0;
        igv = 0.0;
        total = 0.0;
        int rows = dtm.getRowCount();
        int cont = 0;
        while (cont < rows) {
            total = total + Double.parseDouble(dtm.getValueAt(cont, 4).toString());
            cont++;
        }
        subTotal = total / 1.18;
        igv = total - subTotal;
        txtSubTotal.setText(String.format("%.2f", subTotal));
        txtIgv.setText(String.format("%.2f", igv));
        txtTotal.setText(String.format("%.2f", total));
    }
