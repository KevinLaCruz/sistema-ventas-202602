    private void txtBuscarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtBuscarKeyReleased
        // TODO add your handling code here:
        try {
            limpiarTable();
            String nombre = txtBuscar.getText().trim();
            if (!nombre.isEmpty()) {
                rsProducto = objProductoDAO.search(nombre);
                while (rsProducto.next()) {
                    Object[] row = {rsProducto.getInt(1), rsProducto.getString(2)};
                    dtm.addRow(row);
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error: " + e);
        }
    }//GEN-LAST:event_txtBuscarKeyReleased

    private void tblProductoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductoMouseClicked
        // TODO add your handling code here:
        try {
            int xid_producto = Integer.parseInt(tblProducto.getValueAt(tblProducto.getSelectedRow(), 0).toString());
            rsProducto.first();
            do {
                if (xid_producto == rsProducto.getInt(1)) {
                    txtCodigo.setText(String.valueOf(rsProducto.getInt(1)));
                    txtNombre.setText(rsProducto.getString(2));
                    txtPrecio.setText(String.valueOf(rsProducto.getDouble(3)));
                    txtObservacion.setText(rsProducto.getString(4));
                    rsProducto.last();
                }
            } while (rsProducto.next());
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error: " + e);
        }
    }//GEN-LAST:event_tblProductoMouseClicked

    private void btnGrabarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGrabarActionPerformed
        // TODO add your handling code here:
        try {
            String mensaje = "";
            ProductoTO p = new ProductoTO();
            p.setNomb_prod(txtNombre.getText());
            p.setPrec_prod(Double.parseDouble(txtPrecio.getText()));
            p.setObsv_prod(txtObservacion.getText());
            if (sw) {
                objProductoDAO.insert(p);
                mensaje = "Agregado.";
            } else {
                p.setId_producto(Integer.parseInt(txtCodigo.getText()));
                objProductoDAO.update(p);
                mensaje = "Actualizado.";
            }
            JOptionPane.showMessageDialog(rootPane, mensaje);
            habilitarControles(false);
            limpiarControles();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error: " + e);
        }
    }//GEN-LAST:event_btnGrabarActionPerformed

    private void btnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActionPerformed
        // TODO add your handling code here:
        try {
            int op = JOptionPane.showConfirmDialog(rootPane, "¿Borrar?", "Pregunta", JOptionPane.YES_NO_OPTION);
            if (op == JOptionPane.YES_OPTION) {
                ProductoTO p = new ProductoTO();
                p.setId_producto(Integer.parseInt(txtCodigo.getText()));
                objProductoDAO.delete(p);
                JOptionPane.showMessageDialog(rootPane, "Eliminado.");
                limpiarControles();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error: " + e);
        }
    }//GEN-LAST:event_btnBorrarActionPerformed


