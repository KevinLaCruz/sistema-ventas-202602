    public void limpiarTable() {
        if (dtm.getRowCount() > 0) {
            dtm.setRowCount(0);
        }
    }

    public void habilitarControles(boolean b) {
        JTextField[] txt = {txtNombre, txtPrecio, txtObservacion};
        for (JTextField t : txt) {
            t.setEditable(b);
        }
        btnGrabar.setEnabled(b);
        btnCancelar.setEnabled(b);
        btnNuevo.setEnabled(!b);
        btnEditar.setEnabled(!b);
        btnBorrar.setEnabled(!b);
        btnSalir.setEnabled(!b);
        txtNombre.grabFocus();
    }

    public void limpiarControles() {
        limpiarTable();
        JTextField[] txt = {txtBuscar, txtCodigo, txtNombre, txtPrecio, txtObservacion};
        for (JTextField t : txt) {
            t.setText(null);
        }
    }
