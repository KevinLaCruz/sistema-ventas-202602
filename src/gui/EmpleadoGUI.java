    public void habilitarControles(boolean b) {
        JTextField[] txt = {txtDni, txtNombre, txtApPaterno, txtApMaterno, txtDireccion, txtTelefono, txtCelular, txtEmail, txtObservacion};
        for (JTextField t : txt) {
            t.setEditable(b);
        }
        rbtMasculino.setEnabled(b);
        rbtFemenino.setEnabled(b);
        cmbDistrito.setEnabled(b);
        btnCargar.setEnabled(b);
        btnQuitar.setEnabled(b);
        btnGrabar.setEnabled(b);
        btnCancelar.setEnabled(b);
        btnNuevo.setEnabled(!b);
        btnEditar.setEnabled(!b);
        btnBorrar.setEnabled(!b);
        btnSalir.setEnabled(!b);
        txtDni.grabFocus();
    }

    public void limpiarControles() {
        limpiarTable();
        JTextField[] txt = {txtBuscar, txtCodigo, txtDni, txtNombre, txtApPaterno, txtApMaterno, txtDireccion, txtTelefono, txtCelular, txtEmail, txtObservacion};
        for (JTextField t : txt) {
            t.setText(null);
        }
        bg.clearSelection();
        cmbDistrito.removeAllItems();
        nombreFoto = "";
        lblFoto.setIcon(null);
    }

    public void llenaCombo() {
        try {
            Object s = cmbDistrito.getSelectedItem();
            cmbDistrito.removeAllItems();
            rsDistrito = objDistritoDAO.search("%");
            while (rsDistrito.next()) {
                cmbDistrito.addItem(rsDistrito.getString(2));
            }
            cmbDistrito.setSelectedItem(s);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error: " + e);
        }
    }

    public int obtenerIdDistrito() throws Exception {
        Object s = cmbDistrito.getSelectedItem();
        if (s == null) {
            throw new Exception("Seleccione un distrito.");
        }
        String nombre = s.toString();
        try (ResultSet rs = objDistritoDAO.search(nombre)) {
            while (rs.next()) {
                if (nombre.equalsIgnoreCase(rs.getString(2))) {
                    return rs.getInt(1);
                }
            }
        }
        throw new Exception("Distrito no encontrado.");
    }

    public void ajustarImagen(ImageIcon icono) {
        Image img = icono.getImage().getScaledInstance(lblFoto.getWidth(), lblFoto.getHeight(), Image.SCALE_SMOOTH);
        lblFoto.setIcon(new ImageIcon(img));
    }

    public void obtenerAvatar(String sexo) {
        nombreFoto = "";
        String ruta = sexo.equalsIgnoreCase("M") ? "/predeterminado/hombre.png" : "/predeterminado/mujer.png";
        URL recurso = getClass().getResource(ruta);
        if (recurso != null) {
            ajustarImagen(new ImageIcon(recurso));
        } else {
            JOptionPane.showMessageDialog(rootPane, "No se encontró el recurso: " + ruta);
        }
    }
