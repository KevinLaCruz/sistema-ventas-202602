    private void txtBuscarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtBuscarKeyReleased
        // TODO add your handling code here:
        try {
            limpiarTable();
            String nombre = txtBuscar.getText().trim();
            if (!nombre.isEmpty()) {
                rsEmpleado = objEmpleadoDAO.search(nombre);
                while (rsEmpleado.next()) {
                    Object[] row = {rsEmpleado.getInt(1), rsEmpleado.getString(3), rsEmpleado.getString(4), rsEmpleado.getString(5)};
                    dtm.addRow(row);
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error: " + e);
        }
    }//GEN-LAST:event_txtBuscarKeyReleased

    private void tblEmpleadoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblEmpleadoMouseClicked
        // TODO add your handling code here:
        try {
            int xid_empleado = Integer.parseInt(tblEmpleado.getValueAt(tblEmpleado.getSelectedRow(), 0).toString());
            rsEmpleado.first();
            do {
                if (xid_empleado == rsEmpleado.getInt(1)) {
                    txtCodigo.setText(String.valueOf(rsEmpleado.getInt(1)));
                    txtDni.setText(rsEmpleado.getString(2));
                    txtNombre.setText(rsEmpleado.getString(3));
                    txtApPaterno.setText(rsEmpleado.getString(4));
                    txtApMaterno.setText(rsEmpleado.getString(5));
                    if (rsEmpleado.getString(6).equalsIgnoreCase("M")) {
                        rbtMasculino.setSelected(true);
                    }
                    if (rsEmpleado.getString(6).equalsIgnoreCase("F")) {
                        rbtFemenino.setSelected(true);
                    }
                    txtDireccion.setText(rsEmpleado.getString(7));
                    cmbDistrito.removeAllItems();
                    cmbDistrito.addItem(rsEmpleado.getString(8));
                    txtTelefono.setText(rsEmpleado.getString(9));
                    txtCelular.setText(rsEmpleado.getString(10));
                    txtEmail.setText(rsEmpleado.getString(11));
                    txtObservacion.setText(rsEmpleado.getString(12));
                    String foto = rsEmpleado.getString(13);
                    if (foto == null || foto.trim().isEmpty()) {
                        nombreFoto = "";
                        if (rbtMasculino.isSelected()) {
                            ajustarImagen(new ImageIcon(getClass().getResource("/predeterminado/hombre.png")));
                        } else {
                            ajustarImagen(new ImageIcon(getClass().getResource("/predeterminado/mujer.png")));
                        }
                    } else {
                        nombreFoto = foto;
                        ajustarImagen(new ImageIcon("C:\\Users\\Kevin La Cruz\\Pictures\\image\\" + nombreFoto));
                    }
                    rsEmpleado.last();
                }
            } while (rsEmpleado.next());
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error: " + e);
        }
    }//GEN-LAST:event_tblEmpleadoMouseClicked

