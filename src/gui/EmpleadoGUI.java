    private void btnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActionPerformed
        // TODO add your handling code here:
        try {
            int op = JOptionPane.showConfirmDialog(rootPane, "¿Borrar?", "Pregunta", JOptionPane.YES_NO_OPTION);
            if (op == JOptionPane.YES_OPTION) {
                EmpleadoTO e = new EmpleadoTO();
                e.setId_empleado(Integer.parseInt(txtCodigo.getText()));
                objEmpleadoDAO.delete(e);
                JOptionPane.showMessageDialog(rootPane, "Eliminado.");
                limpiarControles();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error: " + e);
        }
    }//GEN-LAST:event_btnBorrarActionPerformed

