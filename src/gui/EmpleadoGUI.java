    private void btnGrabarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGrabarActionPerformed
        // TODO add your handling code here:
        try {
            if (!rbtMasculino.isSelected() && !rbtFemenino.isSelected()) {
                JOptionPane.showMessageDialog(rootPane, "Seleccione un genero.");
                return;
            }
            String mensaje = "";
            EmpleadoTO e = new EmpleadoTO();
            e.setDni_empl(txtDni.getText());
            e.setNomb_empl(txtNombre.getText());
            e.setApat_empl(txtApPaterno.getText());
            e.setAmat_empl(txtApMaterno.getText());
            if (rbtMasculino.isSelected()) {
                e.setSexo_empl("M");
            }
            if (rbtFemenino.isSelected()) {
                e.setSexo_empl("F");
            }
            e.setDire_empl(txtDireccion.getText());
            e.setId_distrito(obtenerIdDistrito());
            e.setTelf_empl(txtTelefono.getText());
            e.setCelu_empl(txtCelular.getText());
            e.setEmai_empl(txtEmail.getText());
            e.setObsv_empl(txtObservacion.getText());
            e.setFoto_empl(nombreFoto);
            if (sw) {
                objEmpleadoDAO.insert(e);
                mensaje = "Agregado.";
            } else {
                e.setId_empleado(Integer.parseInt(txtCodigo.getText()));
                objEmpleadoDAO.update(e);
                mensaje = "Actualizado.";
            }
            JOptionPane.showMessageDialog(rootPane, mensaje);
            habilitarControles(false);
            limpiarControles();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error: " + e);
        }
    }//GEN-LAST:event_btnGrabarActionPerformed

